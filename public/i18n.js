let LANG = localStorage.getItem('dnslab.lang') || 'en';

// 命名避开 t/getLang/setLang：经典脚本的顶层 function 会挂到 window，与 app.js 的 const 解构冲突
function translate(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

const currentLang = () => LANG;

function applyStatic() {
  document.documentElement.lang = LANG === 'zh' ? 'zh-CN' : 'en';
  document.title = translate('app.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = translate(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = translate(el.getAttribute('data-i18n-html')); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = translate(el.getAttribute('data-i18n-ph')); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = translate(el.getAttribute('data-i18n-title')); });
}

function changeLang(lang) {
  LANG = I18N[lang] ? lang : 'en';
  localStorage.setItem('dnslab.lang', LANG);
  applyStatic();
  document.dispatchEvent(new CustomEvent('dnslab:lang'));
}

applyStatic();
window.I18n = { t: translate, getLang: currentLang, setLang: changeLang, applyStatic };
